#!/usr/bin/env python3
"""Generate embedded benchmark assets so the EPUB + image-decode steps run with
NO SD card attached.

Outputs (regenerate any time, any size):
  src/sample_chapter.h  SAMPLE_XHTML    — a few chapters of synthetic prose with
                        headings, paragraphs, a blockquote and <img> tags.
  src/sample_images.h   SAMPLE_IMAGES[] — grayscale JPEGs for the decode step.

The prose is synthetic (public-domain-style word salad) — no copyrighted text;
exact wording is irrelevant to a pagination benchmark, only length/word-shape.
The <img> tags in the XHTML are DROPPED by the benchmark's stripTags — images
are exercised separately by the JPEG-decode step (reads sample_images.h directly).

Requires Pillow (`pip install pillow`). Deterministic (fixed seed).

Usage: make_sample.py [chapters] [words_per_chapter]
       defaults: 3 chapters x 1400 words  (~40 KB of XHTML)
"""

import io
import random
import sys
import zlib
from pathlib import Path

from PIL import Image, ImageDraw

SEED = 20260722
SRC = Path(__file__).resolve().parent.parent / "src"

WORDS = (
    "the of and to a in that it was his he for as with had not but be at her "
    "by on she which have this from all were they would there their what so up "
    "out if about who get me when make can like time just him know take people "
    "into year good some could see other than then now look only come over "
    "think also back after use morning garden letter friend country evening "
    "manner however therefore acquaintance particular immediately circumstance "
    "conversation happiness sentiment sister mother daughter gentleman marriage "
    "fortune character opinion neighbourhood consideration understanding"
).split()


def sentence(rng):
    n = rng.randint(6, 18)
    words = [rng.choice(WORDS) for _ in range(n)]
    words[0] = words[0].capitalize()
    if rng.random() < 0.15:  # occasional inline emphasis
        i = rng.randrange(len(words))
        tag = rng.choice(("em", "strong"))
        words[i] = f"<{tag}>{words[i]}</{tag}>"
    return " ".join(words) + rng.choice((".", ".", ".", "?", "!"))


def paragraph(rng):
    return " ".join(sentence(rng) for _ in range(rng.randint(3, 8)))


def build_xhtml(chapters, words_per_chapter):
    rng = random.Random(SEED)
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<html xmlns="http://www.w3.org/1999/xhtml"><head>'
        "<title>Benchmark Sample</title></head><body>",
    ]
    for c in range(1, chapters + 1):
        out.append(f"<h1>Chapter {c}</h1>")
        if c == 1:  # a chapter-opening image (dropped by stripTags)
            out.append('<img src="images/plate1.jpg" alt="frontispiece"/>')
        words = 0
        section = 1
        while words < words_per_chapter:
            if rng.random() < 0.18:
                out.append(f"<h2>Section {c}.{section}</h2>")
                section += 1
            if c == 2 and section == 2 and rng.random() < 0.4:
                out.append('<img src="images/figure1.jpg" alt="figure"/>')
            if rng.random() < 0.08:
                out.append(f"<blockquote>{paragraph(rng)}</blockquote>")
            para = paragraph(rng)
            out.append(f"<p>{para}</p>")
            words += len(para.split())
    out.append("</body></html>")
    return "\n".join(out)


def emit_text_header(xhtml):
    delim = "EPUBSAMPLE"
    assert f"){delim}\"" not in xhtml, "raw-string delimiter clash"
    (SRC / "sample_chapter.h").write_text(
        "#pragma once\n"
        "#include <stddef.h>\n"
        "// AUTO-GENERATED by tools/make_sample.py — do not edit by hand.\n"
        "// Synthetic public-domain-style prose. <img> tags are dropped by\n"
        "// stripTags; images are exercised via sample_images.h instead.\n"
        f'static const char SAMPLE_XHTML[] = R"{delim}(\n{xhtml}\n){delim}";\n'
        "static const size_t SAMPLE_XHTML_LEN = sizeof(SAMPLE_XHTML) - 1;\n"
    )
    return len(xhtml)


def make_jpeg(w, h, seed):
    rng = random.Random(seed)
    img = Image.new("L", (w, h), 255)
    draw = ImageDraw.Draw(img)
    for x in range(w):  # horizontal gradient
        draw.line([(x, 0), (x, h)], fill=int(255 * x / w))
    for _ in range(14):  # shapes → high-frequency detail to stress decode+dither
        x0, y0 = rng.randint(0, w - 1), rng.randint(0, h - 1)
        x1 = min(w - 1, x0 + rng.randint(10, w // 3))
        y1 = min(h - 1, y0 + rng.randint(10, h // 3))
        shade = rng.randint(0, 255)
        (draw.rectangle if rng.random() < 0.5 else draw.ellipse)(
            [x0, y0, x1, y1], outline=shade
        )
    draw.text((8, 8), "PLATE", fill=0)
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=80)
    return buf.getvalue()


def emit_images_header(images):
    lines = [
        "#pragma once",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "// AUTO-GENERATED by tools/make_sample.py — grayscale JPEG test images.",
        "",
    ]
    for i, (_name, data) in enumerate(images):
        arr = ", ".join(str(b) for b in data)
        lines.append(f"static const uint8_t IMG{i}_JPG[] = {{{arr}}};")
        lines.append(f"static const size_t IMG{i}_JPG_LEN = sizeof(IMG{i}_JPG);")
    lines += [
        "",
        "struct SampleImage { const uint8_t* data; size_t len; const char* name; };",
        "static const SampleImage SAMPLE_IMAGES[] = {",
    ]
    for i, (name, _data) in enumerate(images):
        lines.append(f'  {{IMG{i}_JPG, IMG{i}_JPG_LEN, "{name}"}},')
    lines += ["};", f"static const size_t SAMPLE_IMAGE_COUNT = {len(images)};", ""]
    (SRC / "sample_images.h").write_text("\n".join(lines))


def emit_deflate_header(raw):
    comp = zlib.compress(raw, 6)  # zlib format — matches zlib's uncompress()
    arr = ", ".join(str(b) for b in comp)
    (SRC / "sample_deflate.h").write_text(
        "#pragma once\n"
        "#include <stdint.h>\n"
        "#include <stddef.h>\n"
        "// AUTO-GENERATED by tools/make_sample.py — zlib-compressed prose for the\n"
        "// inflate-throughput benchmark (decompressed on-device with zlib uncompress).\n"
        f"static const uint8_t DEFLATE_DATA[] = {{{arr}}};\n"
        f"static const size_t DEFLATE_DATA_LEN = sizeof(DEFLATE_DATA);\n"
        f"static const size_t DEFLATE_ORIG_LEN = {len(raw)};\n"
    )
    return len(comp)


def main():
    chapters = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    wpc = int(sys.argv[2]) if len(sys.argv) > 2 else 1400
    xhtml = build_xhtml(chapters, wpc)
    n = emit_text_header(xhtml)
    comp_len = emit_deflate_header(xhtml.encode("utf-8"))
    images = [
        ("plate-480x320", make_jpeg(480, 320, 1)),
        ("figure-240x240", make_jpeg(240, 240, 2)),
    ]
    emit_images_header(images)
    print(f"sample_chapter.h: {chapters} chapters, {n} bytes XHTML")
    print(f"sample_deflate.h: {n} -> {comp_len} bytes zlib ({comp_len * 100 // n}%)")
    for name, data in images:
        print(f"sample_images.h:  {name} -> {len(data)} bytes JPEG")


if __name__ == "__main__":
    main()
