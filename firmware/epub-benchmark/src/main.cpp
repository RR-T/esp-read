// Crude XHTML->text: drop tags, decode a few entities, collapse whitespace.
static size_t stripTags(const char *in, size_t n, char *out) {
  size_t o = 0;
  bool inTag = false, lastSpace = false;
  for (size_t i = 0; i < n; i++) {
    char c = in[i];
    if (c == '<') { inTag = true; continue; }
    if (c == '>') {  // tag boundary becomes whitespace
      inTag = false;
      if (!lastSpace) { out[o++] = ' '; lastSpace = true; }
      continue;
    }
    if (inTag) continue;
    if (c == '&') {  // minimal entity handling
      if (!strncmp(in + i, "&amp;", 5)) { out[o++] = '&'; i += 4; }
      else if (!strncmp(in + i, "&lt;", 4)) { out[o++] = '<'; i += 3; }
      else if (!strncmp(in + i, "&gt;", 4)) { out[o++] = '>'; i += 3; }
      else if (!strncmp(in + i, "&#", 2)) { while (i < n && in[i] != ';') i++; out[o++] = ' '; }
      else out[o++] = '&';
      lastSpace = false;
      continue;
    }
    if (isspace((unsigned char)c)) {
      if (!lastSpace) { out[o++] = ' '; lastSpace = true; }
    } else {
      out[o++] = c;
      lastSpace = false;
    }
  }
  out[o] = 0;
  return o;
}

// JPEGDEC draws in MCU blocks; 8-bit grayscale in, 4x4 Bayer ordered-dither out
// to the 1-bit canvas (dark pixel -> ink). Same idea as CrossPoint's DitherUtils.
static int jpegDraw(JPEGDRAW *pDraw) {
  if (!canvas) return 1;
  static const uint8_t bayer[4][4] = {
      {0, 8, 2, 10}, {12, 4, 14, 6}, {3, 11, 1, 9}, {15, 7, 13, 5}};
  const uint8_t *g = (const uint8_t *)pDraw->pPixels;  // EIGHT_BIT_GRAYSCALE
  for (int j = 0; j < pDraw->iHeight; j++) {
    int y = pDraw->y + j;
    if ((unsigned)y >= (unsigned)Epd5in0::HEIGHT) continue;
    for (int i = 0; i < pDraw->iWidth; i++) {
      int x = pDraw->x + i;
      if ((unsigned)x >= (unsigned)Epd5in0::WIDTH) continue;
      int thresh = bayer[y & 3][x & 3] * 16 + 8;       // 0..255
      canvas->drawPixel(x, y, g[j * pDraw->iWidth + i] < thresh ? 1 : 0);
    }
  }
  return 1;
}

static void benchImages() {
  rule("Image decode (embedded JPEG)");
  if (!canvas) { Serial.println("  (no canvas — skipped)"); return; }
  for (size_t k = 0; k < SAMPLE_IMAGE_COUNT; k++) {
    const SampleImage &im = SAMPLE_IMAGES[k];
    if (!jpeg.openRAM((uint8_t *)im.data, (int)im.len, jpegDraw)) {
      Serial.printf("  %-16s openRAM FAILED\n", im.name);
      continue;
    }
    jpeg.setPixelType(EIGHT_BIT_GRAYSCALE);
    int w = jpeg.getWidth(), h = jpeg.getHeight();
    canvas->fillScreen(0);
    uint32_t t0 = micros();
    int ok = jpeg.decode(MARGIN_X, TOP, 0);  // decode + dither into the canvas
    uint32_t us = micros() - t0;
    jpeg.close();
    Serial.printf("  %-16s %dx%d  decode+dither %lu us  %s\n", im.name, w, h,
                  (unsigned long)us, ok ? "" : "(DECODE FAIL)");
    if (panelOk) epd.displayFull(canvas->getBuffer(), /*invert=*/true);
  }
  reportMem("after images");
}

// Strip tags -> paginate -> render page 1, timing each step with heap watermarks.
// `raw` may live in flash (embedded sample) or PSRAM (SD read).
static void processChapter(const char *raw, size_t got, const char *label) {
  Serial.printf("  source          %s (%u bytes)\n", label, (unsigned)got);
  reportMem("before");

  char *text = (char *)heap_caps_malloc(got + 1, MALLOC_CAP_SPIRAM);
  if (!text) { Serial.println("  text alloc FAILED (too big?)"); return; }

  uint32_t t0 = micros();
  size_t tlen = stripTags(raw, got, text);
  Serial.printf("  strip tags      %lu us -> %u chars text\n",
                (unsigned long)(micros() - t0), (unsigned)tlen);

  if (canvas) {
    t0 = millis();
    int pages = paginate(text, false);  // measure full pagination cost
    uint32_t pagMs = millis() - t0;
    t0 = micros();
    paginate(text, true);               // render page 1
    Serial.printf("  paginate (all)  %lu ms -> %d pages\n", pagMs, pages);
    Serial.printf("  render page 1   %lu us\n", (unsigned long)(micros() - t0));
    if (panelOk) epd.displayFull(canvas->getBuffer(), true);
  }

  reportMem("after");
  Serial.printf("  min internal free since boot: %u  | min PSRAM free: %u\n",
                (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_INTERNAL),
                (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_SPIRAM));
  free(text);
}

static void benchEpub() {
  rule("EPUB-style workload");

  const char *path = nullptr;
  if (sdOk)
    path = SD.exists("/sample.xhtml") ? "/sample.xhtml"
           : SD.exists("/sample.txt") ? "/sample.txt"
                                      : nullptr;

  if (path) {
    File f = SD.open(path);
    size_t n = f.size();
    char *raw = (char *)heap_caps_malloc(n + 1, MALLOC_CAP_SPIRAM);
    if (!raw) { Serial.println("  raw alloc FAILED (file too big?)"); f.close(); return; }
    uint32_t t0 = millis();
    size_t got = f.read((uint8_t *)raw, n);
    raw[got] = 0;
    f.close();
    Serial.printf("  SD read         %lu ms (%.2f MB/s)\n", millis() - t0,
                  (double)got / 1024.0 / 1024.0 / ((millis() - t0) / 1000.0 + 1e-6));
    processChapter(raw, got, path);
    free(raw);
  } else {
    Serial.println("  no SD card — using embedded sample (tools/make_sample.py)");
    processChapter(SAMPLE_XHTML, SAMPLE_XHTML_LEN, "embedded SAMPLE_XHTML");
  }
}

// --------------------------------------------------------------------------
void setup() {
  g_bootUs = esp_timer_get_time();  // app-init latency — capture before anything else
  Serial.begin(115200);
  uint32_t start = millis();
  // Wait for the USB-CDC host: with `pio run -t upload -t monitor` the monitor
  // can attach a few seconds after the post-flash reset, so give it room or the
  // top of the report (incl. the PSRAM line) prints before you're connected.
  while (!Serial && millis() - start < 10000) delay(10);
  delay(300);

#if BENCH_SLEEP_CYCLES > 0
  if (esp_sleep_get_wakeup_cause() == ESP_SLEEP_WAKEUP_TIMER) {
    Serial.printf("deep-sleep wake #%d: app-ready in %.1f ms\n", g_wakeCycle,
                  g_bootUs / 1000.0);
    if (++g_wakeCycle < BENCH_SLEEP_CYCLES) {
      Serial.flush();
      esp_sleep_enable_timer_wakeup(2ULL * 1000000ULL);
      esp_deep_sleep_start();  // does not return
    }
    Serial.println("deep-sleep wake-latency loop complete.");
    return;  // skip the full report on wake cycles
  }
#endif

  Serial.println("\n\n######## esp-read on-device EPUB benchmark ########");

  benchWake();
  reportBoard();
  benchPsram();
  benchClock();
#if HAVE_INFLATE
  benchInflate();
#endif
  initBus();
  // Panel protection: sleep the panel between bench stages so the film is never
  // left energised across the whole run. Waking needs a reset after 0x10, so
  // epd.begin() re-inits before the next stage draws. PWR stays HIGH across the
  // run (sleep already drops the HV rails); it's cut once at the very end.
  benchRefresh();
  if (panelOk) { epd.sleep(); epd.begin(); }
  benchRender();
  if (panelOk) { epd.sleep(); epd.begin(); }
  benchImages();
  if (panelOk) { epd.sleep(); epd.begin(); }
  benchEpub();
  if (panelOk) epd.sleep();

  rule("Done");
  // Recap the numbers that gate the CrossPoint feasibility call, so they're
  // readable at the tail even if the top of the report scrolled past on attach.
  Serial.printf("  PSRAM: %u total / %u free%s\n",
                (unsigned)ESP.getPsramSize(), (unsigned)ESP.getFreePsram(),
                ESP.getPsramSize() == 0 ? "  !! NOT DETECTED (try memory_type qio_qspi)" : "");
  Serial.printf("  min free since boot: internal %u | PSRAM %u\n",
                (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_INTERNAL),
                (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_SPIRAM));
  Serial.printf("  loop-task stack high-water: %u bytes free\n",
                (unsigned)(uxTaskGetStackHighWaterMark(NULL) * sizeof(StackType_t)));
  Serial.println("  Reading guide:");
  Serial.println("   - full refresh ~1.8s / partial ~0.7s is expected for this panel");
  Serial.println("   - page render should be well under a few hundred ms");
  Serial.println("   - pagination time x pages = cold-open cost; if large, cache it to flash");
  Serial.println("   - watch 'min internal free' — fragmentation, not PSRAM, is the usual limit");

  // Panel shutdown (lifecycle). Clear to WHITE so the panel isn't left holding a
  // stale static image during idle/storage — e-paper is bistable, so whatever is
  // on screen persists with power off (Waveshare: "store it with a white image").
  // Then deep-sleep the controller, wait >=2s for the HV rails to discharge, and
  // cut PWR (0-power). The real reader does the same on low-battery/idle/storage
  // shutdown. (Waveshare EPD_5in0: Sleep() -> >=2s -> DEV_Module_Exit().)
  if (panelOk) {
    epd.begin();        // wake from the between-stage deep sleep (needs a reset)
    epd.clearWhite();   // leave the panel WHITE, not the last EPUB page
    epd.sleep();
    delay(2000);        // HV-rail discharge before removing power
  }
  digitalWrite(EPD_PWR, LOW);

#if BENCH_SLEEP_CYCLES > 0
  Serial.printf("\nStarting deep-sleep wake-latency loop (%d cycles, 2s each)...\n",
                BENCH_SLEEP_CYCLES);
  Serial.println("(the USB monitor drops on each sleep — reopen it to catch each wake line)");
  g_wakeCycle = 0;
  Serial.flush();
  esp_sleep_enable_timer_wakeup(2ULL * 1000000ULL);
  esp_deep_sleep_start();
#endif
}

