// miniz's tinfl_decompress_mem_to_mem() puts an ~11 KB decompressor struct on the
// caller's stack, which overflows the default 8 KB loop-task stack. Bump it. (The
// real firmware will use a heap/streaming inflate — uzlib — so this is a quirk of
// the convenience wrapper, not a sign on-device inflate is expensive.)
SET_LOOP_TASK_STACK_SIZE(16 * 1024);

